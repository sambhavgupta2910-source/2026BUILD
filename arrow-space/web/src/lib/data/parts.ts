// --- Helpers --------------------------------------------------------------

export function getPart(partNumber: string): Part | undefined {
  return parts.find(
    (p) => p.partNumber.toLowerCase() === partNumber.toLowerCase(),
  );
}

export function totalStock(part: Part): number {
  return part.stock.reduce((sum, s) => sum + s.quantity, 0);
}

export function bestLeadTime(part: Part): number | null {
  const inStock = part.stock.filter((s) => s.quantity > 0);
  if (inStock.length === 0) return null;
  return Math.min(...inStock.map((s) => s.leadTimeDays));
}

export const ataChapters = Array.from(
  new Set(parts.map((p) => p.ataChapter)),
).sort();

export const categories = Array.from(
  new Set(parts.map((p) => p.category)),
).sort();

export const aircraftTypes = Array.from(
  new Set(parts.flatMap((p) => p.aircraft)),
).sort();
